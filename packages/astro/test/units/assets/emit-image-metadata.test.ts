import { describe, it } from 'node:test';
import { writeFile, mkdir, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { emitImageMetadata } from '../../../dist/assets/utils/node.js';

const APNG_FIXTURE = fileURLToPath(
	new URL('../../fixtures/core-image-errors/src/images/animated.apng', import.meta.url),
);

// Minimal valid 1×1 JPEG
const TINY_JPEG = Buffer.from([
	0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01,
	0x00, 0x01, 0x00, 0x00, 0xff, 0xdb, 0x00, 0x43, 0x00, 0x08, 0x06, 0x06, 0x07, 0x06, 0x05, 0x08,
	0x07, 0x07, 0x07, 0x09, 0x09, 0x08, 0x0a, 0x0c, 0x14, 0x0d, 0x0c, 0x0b, 0x0b, 0x0c, 0x19, 0x12,
	0x13, 0x0f, 0x14, 0x1d, 0x1a, 0x1f, 0x1e, 0x1d, 0x1a, 0x1c, 0x1c, 0x20, 0x24, 0x2e, 0x27, 0x20,
	0x22, 0x2c, 0x23, 0x1c, 0x1c, 0x28, 0x37, 0x29, 0x2c, 0x30, 0x31, 0x34, 0x34, 0x34, 0x1f, 0x27,
	0x39, 0x3d, 0x38, 0x32, 0x3c, 0x2e, 0x33, 0x34, 0x32, 0xff, 0xc0, 0x00, 0x0b, 0x08, 0x00, 0x01,
	0x00, 0x01, 0x01, 0x01, 0x11, 0x00, 0xff, 0xc4, 0x00, 0x1f, 0x00, 0x00, 0x01, 0x05, 0x01, 0x01,
	0x01, 0x01, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
	0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f,
	0x00, 0x7b, 0x40, 0x1f, 0xff, 0xd9,
]);

describe('emitImageMetadata', () => {
	it('returns undefined for undefined id', async () => {
		const result = await emitImageMetadata(undefined);
		assert.equal(result, undefined);
	});

	it('returns undefined when image file does not exist (ENOENT)', async () => {
		const result = await emitImageMetadata('/tmp/nonexistent-image-abc123.jpg');
		assert.equal(result, undefined);
	});

	it('returns metadata for an existing image', async () => {
		const dir = join(tmpdir(), `astro-test-${Date.now()}`);
		const file = join(dir, 'test.jpg');
		await mkdir(dir, { recursive: true });
		try {
			await writeFile(file, TINY_JPEG);
			const result = await emitImageMetadata(file);
			assert.ok(result, 'expected metadata to be returned');
			assert.equal(result.width, 1);
			assert.equal(result.height, 1);
			assert.equal(result.format, 'jpg');
		} finally {
			await rm(dir, { recursive: true, force: true });
		}
	});

	it('returns APNG metadata with dimensions', async () => {
		const result = await emitImageMetadata(APNG_FIXTURE);
		assert.ok(result, 'expected metadata to be returned');
		assert.equal(result.width, 2);
		assert.equal(result.height, 3);
		assert.equal(result.format, 'apng');
	});
});
